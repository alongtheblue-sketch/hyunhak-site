def main():
    dry = "--dry-run" in sys.argv
    m = C.load_manifest()
    fails = []
    for rel, upd in HAND.items():
        if rel not in m["pages"]:
            fails.append(f"{rel}: manifest 미등재"); continue
        d = upd.get("description")
        if d is not None and not 70 <= len(d) <= 110:
            fails.append(f"{rel}: description {len(d)}자")
        a = upd.get("answer")
        if a is not None and not 40 <= len(a) <= 110:
            fails.append(f"{rel}: answer {len(a)}자")
        for k, v in upd.items():
            txt = " ".join(v) if isinstance(v, list) else v
            if any(ch in txt for ch in ("·", "—")):
                fails.append(f"{rel}: {k} 가운뎃점/em대시")
        m["pages"][rel].update(upd)
    m["site"]["llms"]["keywords"] = LLMS_KEYWORDS
    titles = {}
    for rel, e in m["pages"].items():
        titles.setdefault(e.get("title"), []).append(rel)
    for t, rels in titles.items():
        if t and len(rels) > 1:
            fails.append(f"title 중복 {t!r}: {rels}")
    if fails:
        sys.exit("apply_seo_keywords FAIL: " + "; ".join(fails))
    if not dry:
        C.save_manifest(m)
    print(f"apply_seo_keywords: {len(HAND)}면 + llms keywords {len(LLMS_KEYWORDS)}개 {'(dry-run)' if dry else '기록'}")


if __name__ == "__main__":
    main()
